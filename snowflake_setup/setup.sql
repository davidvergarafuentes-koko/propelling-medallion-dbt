-- Run once as ACCOUNTADMIN in a Snowflake worksheet (Run All).
-- Creates the warehouse, database, layer schemas, roles and the dbt service user.
USE ROLE ACCOUNTADMIN;

-- Compute: smallest size, pauses after 60 idle seconds to save trial credits
CREATE WAREHOUSE IF NOT EXISTS TRANSFORM_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

-- Storage: our own database with one schema per Medallion layer
CREATE DATABASE IF NOT EXISTS PROPELLING_DB;
CREATE SCHEMA IF NOT EXISTS PROPELLING_DB.BRONZE;
CREATE SCHEMA IF NOT EXISTS PROPELLING_DB.SILVER;
CREATE SCHEMA IF NOT EXISTS PROPELLING_DB.GOLD;

-- TRANSFORMER: what dbt runs as. Can build in our database and read the sample data.
CREATE ROLE IF NOT EXISTS TRANSFORMER;
GRANT USAGE, OPERATE ON WAREHOUSE TRANSFORM_WH TO ROLE TRANSFORMER;
GRANT ALL ON DATABASE PROPELLING_DB TO ROLE TRANSFORMER;
GRANT ALL ON ALL SCHEMAS IN DATABASE PROPELLING_DB TO ROLE TRANSFORMER;

-- REPORTER: for BI consumers. Can read Gold only.
CREATE ROLE IF NOT EXISTS REPORTER;
GRANT USAGE ON WAREHOUSE TRANSFORM_WH TO ROLE REPORTER;
GRANT USAGE ON DATABASE PROPELLING_DB TO ROLE REPORTER;
GRANT USAGE ON SCHEMA PROPELLING_DB.GOLD TO ROLE REPORTER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PROPELLING_DB.GOLD TO ROLE REPORTER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA PROPELLING_DB.GOLD TO ROLE REPORTER;

